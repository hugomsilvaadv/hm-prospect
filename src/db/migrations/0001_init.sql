CREATE TABLE IF NOT EXISTS leads (
id INTEGER PRIMARY KEY AUTOINCREMENT, handle TEXT NOT NULL UNIQUE,
display_name TEXT NOT NULL DEFAULT '', bio TEXT NOT NULL DEFAULT '',
origin TEXT NOT NULL DEFAULT 'manual', segment TEXT NOT NULL DEFAULT '',
flow TEXT NOT NULL DEFAULT 'customers', score INTEGER NOT NULL DEFAULT 0,
pipeline TEXT NOT NULL DEFAULT 'discovered', channel TEXT NOT NULL DEFAULT 'browser_contact_pending',
meta_user_id TEXT, inbound_at INTEGER, next_action_at INTEGER,
opted_out INTEGER NOT NULL DEFAULT 0, last_error TEXT,
created_at INTEGER NOT NULL, updated_at INTEGER NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS lead_handle_unique ON leads(handle);
CREATE INDEX IF NOT EXISTS lead_meta_idx ON leads(meta_user_id);
CREATE TABLE IF NOT EXISTS messages (
id INTEGER PRIMARY KEY AUTOINCREMENT, lead_id INTEGER NOT NULL REFERENCES leads(id),
external_id TEXT UNIQUE, direction TEXT NOT NULL, channel TEXT NOT NULL,
body TEXT NOT NULL, variant TEXT NOT NULL DEFAULT 'baseline', created_at INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS jobs (
id INTEGER PRIMARY KEY AUTOINCREMENT,kind TEXT NOT NULL,lead_id INTEGER REFERENCES leads(id),
payload TEXT NOT NULL DEFAULT '{}',status TEXT NOT NULL DEFAULT 'queued',
due_at INTEGER NOT NULL, attempts INTEGER NOT NULL DEFAULT 0,last_error TEXT,created_at INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS job_status_due_idx ON jobs(status,due_at);
CREATE TABLE IF NOT EXISTS events (
id INTEGER PRIMARY KEY AUTOINCREMENT,lead_id INTEGER REFERENCES leads(id),
type TEXT NOT NULL,detail TEXT NOT NULL DEFAULT '{}',created_at INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS system (key TEXT PRIMARY KEY, value TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS ai_calls (
id INTEGER PRIMARY KEY AUTOINCREMENT,lead_id INTEGER REFERENCES leads(id),
model TEXT NOT NULL,prompt_tokens INTEGER NOT NULL DEFAULT 0,
completion_tokens INTEGER NOT NULL DEFAULT 0,estimated_cost_usd REAL NOT NULL DEFAULT 0,created_at INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS experiments (
id INTEGER PRIMARY KEY AUTOINCREMENT,name TEXT NOT NULL,
variant_a TEXT NOT NULL,variant_b TEXT NOT NULL,enabled INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS webhook_events (id TEXT PRIMARY KEY,received_at INTEGER NOT NULL);
